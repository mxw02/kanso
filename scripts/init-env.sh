#!/usr/bin/env sh
set -eu

ENV_FILE=".env"
FORCE=0
VERSION="${KANSO_VERSION:-latest}"

while [ "$#" -gt 0 ]; do
  case "$1" in
    -f|--force)
      FORCE=1
      shift
      ;;
    -v|--version)
      VERSION="${2:?Missing value for $1}"
      shift 2
      ;;
    -o|--output)
      ENV_FILE="${2:?Missing value for $1}"
      shift 2
      ;;
    -h|--help)
      echo "Usage: $0 [--force] [--version latest|dev|X.Y.Z] [--output .env]"
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      exit 1
      ;;
  esac
done

if [ -f "$ENV_FILE" ] && [ "$FORCE" -ne 1 ]; then
  echo "$ENV_FILE already exists. Use --force to overwrite (warning: changing ENCRYPTION_KEY invalidates encrypted tokens)." >&2
  exit 1
fi

gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    LC_ALL=C tr -dc 'a-f0-9' </dev/urandom | head -c 64
  fi
}

JWT_SECRET="$(gen_secret)"
ENCRYPTION_KEY="$(gen_secret)"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by scripts/init-env.sh
JWT_SECRET=${JWT_SECRET}
ENCRYPTION_KEY=${ENCRYPTION_KEY}
KANSO_VERSION=${VERSION}
EOF

chmod 600 "$ENV_FILE"
echo "Created $ENV_FILE with fresh JWT_SECRET and ENCRYPTION_KEY (KANSO_VERSION=${VERSION})."
